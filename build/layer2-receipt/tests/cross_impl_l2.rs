/// The PKI the generator built: nodes 1..=7 from the seed `[id; 32]`.
fn golden_pki() -> Pki {
    vectors()["identities"]
        .as_array()
        .unwrap()
        .iter()
        .map(|id| {
            let n = id["node_id"].as_u64().unwrap() as u32;
            (n, Identity::from_secret(n, &[n as u8; 32]).public())
        })
        .collect()
}

/// Rebuild a contribution from a golden record under an explicit context.
///
/// The context is a PARAMETER rather than `golden_ctx()` because the chosen-nonce fixtures
/// were signed under `NO_CONTEXT` and the signature covers the context; a helper that
/// assumed one context could not express the #84 case at all.
fn mk_ctx(ctx: [u8; 32], c: &Value) -> Contribution {
    Contribution {
        ctx,
        sig_preimage: acfa_receipt::identity::PreimageVersion::V2,
        params: PARAMS_DEFAULT,
        rnd: c["rnd"].as_u64().unwrap(),
        node_id: c["node_id"].as_u64().unwrap() as u32,
        tensor: i64s(&c["tensor"]),
        sig: h64(&c["sig"]),
    }
}

fn rule_of(v: &Value) -> Rule {
    match v.as_str().unwrap() {
        "bulyan" => Rule::Bulyan,
        "krum" => Rule::Krum,
        other => panic!("golden names an unknown rule: {other}"),
    }
}

/// Leaves of a state's proof set, hex, sorted -- the form the golden records them in.
fn proof_leaves(s: &State) -> Vec<String> {
    let mut v: Vec<String> = s.e.keys().map(hex::encode).collect();
    v.sort();
    v
}

fn hexes(v: &Value) -> Vec<String> {
    v.as_array()
        .unwrap()
        .iter()
        .map(|x| x.as_str().unwrap().to_string())
        .collect()
}

fn ids(v: &Value) -> Vec<u32> {
    v.as_array()
        .unwrap()
        .iter()
        .map(|x| x.as_u64().unwrap() as u32)
        .collect()
}

/// #84. TWO DISTINCT VALID SIGNATURES OVER ONE CONTENT.
///
/// Every equivocation vector in this file is two different TENSORS, which any implementation
/// separates on the tensor hash. This is the case that separates them only on the LEAF.
/// Ed25519 verification checks `S*B == R + H(R,A,M)*A` and nothing in that equation pins
/// `R`, so one signer can emit two valid signatures over one message. `admit` excludes the
/// identity either way -- on leaf uniqueness -- so the visible symptom is not a missed
/// exclusion but an exclusion WITH NO ACCOUNTABILITY ARTEFACT, which an observer cannot
/// distinguish from a node that went quiet.
///
/// The fixtures are the same constants as `tests/crypto04_nonce_equivocation.rs`, carried
/// through the golden generator, so the unit test and this cross-implementation vector are
/// provably about the same bytes rather than about two independently minted pairs.
#[test]
fn two_signatures_over_one_content_convict_in_both_implementations() {
    let v = vectors();
    let e = &v["nonce_equivocation"];
    let pki = golden_pki();
    let ctx = h32(&e["ctx"]);
    let rnd = e["rnd"].as_u64().unwrap();

    let mk = |sig: &Value| Contribution {
        ctx,
        sig_preimage: acfa_receipt::identity::PreimageVersion::V2,
        params: PARAMS_DEFAULT,
        rnd,
        node_id: e["node_id"].as_u64().unwrap() as u32,
        tensor: i64s(&e["tensor"]),
        sig: h64(sig),
    };
    let (a, b) = (mk(&e["sig_a"]), mk(&e["sig_b"]));

    // The premise, checked before anything rests on it: both are genuinely authored, the
    // CONTENT is identical, and only the LEAF differs. If this fails the fixtures are stale
    // rather than the fix regressed -- see crypto04_nonce_equivocation.rs.
    assert!(
        a.signature_valid(&pki) && b.signature_valid(&pki),
        "the chosen-nonce fixtures no longer verify: the signed preimage moved, so this \
         vector is stale rather than divergent. Regenerate them together with the identical \
         constants in tests/crypto04_nonce_equivocation.rs."
    );
    assert_eq!(a.tensor_hash().to_vec(), hx(&e["tensor_hash"]));
    assert_eq!(
        a.tensor_hash(),
        b.tensor_hash(),
        "one content, by construction"
    );
    assert_ne!(
        a.leaf(),
        b.leaf(),
        "two leaves: the signature is in the leaf"
    );
    assert_eq!(a.leaf().to_vec(), hx(&e["leaf_a"]), "leaf A");
    assert_eq!(b.leaf().to_vec(), hx(&e["leaf_b"]), "leaf B");

    let mut s = State::new();
    s.deliver(a.clone(), &pki);
    s.deliver(b.clone(), &pki);

    assert_eq!(
        proof_leaves(&s),
        hexes(&e["proof_leaves"]),
        "the derived proof must be the reference's proof, byte for byte -- a reference whose \
         EquivProof::valid refuses on h1 == h2 alone finds none here, which makes the \
         leaf-keying fix inert in the normative artefact while this crate convicts"
    );
    assert_eq!(
        s.convicted(&pki).into_iter().collect::<Vec<u32>>(),
        ids(&e["convicted"]),
        "conviction set"
    );
    assert_eq!(s.root().to_vec(), hx(&e["state_root"]), "state root");

    // Order-invariance, on the one shape where both halves are the same content.
    let mut rev = State::new();
    rev.deliver(b, &pki);
    rev.deliver(a, &pki);
    assert_eq!(
        rev.root().to_vec(),
        hx(&e["reverse_state_root"]),
        "reverse-order state root"
    );
    assert_eq!(
        rev.root(),
        s.root(),
        "the state root is a function of the SET"
    );

    let r = acfa_receipt::resolve(
        &s,
        rnd,
        &pki,
        e["f"].as_u64().unwrap() as usize,
        rule_of(&e["rule"]),
    );
    assert_eq!(
        r.admitted.len(),
        ids(&e["admitted_ids"]).len(),
        "an equivocator's contributions must not be aggregated"
    );
    assert_eq!(r.aggregate, None);
    assert_eq!(r.output_root.to_vec(), hx(&e["output_root"]), "output root");

    // POSITIVE CONTROL, and it is not optional. Gossip is at-least-once, so ONE entry
    // arriving twice is the normal case. A detector that convicted here would satisfy every
    // assertion above and convict every honest node in any real deployment.
    let ctl = &e["redelivery_control"];
    let mut once = State::new();
    let dup = mk(&e["sig_a"]);
    once.deliver(dup.clone(), &pki);
    once.deliver(dup, &pki);
    assert_eq!(
        proof_leaves(&once),
        hexes(&ctl["proof_leaves"]),
        "control: redelivering ONE entry is idempotent, not equivocation"
    );
    assert!(
        once.convicted(&pki).is_empty(),
        "control: an honest node whose entry was gossiped twice must not be convicted"
    );
    assert_eq!(
        once.root().to_vec(),
        hx(&ctl["state_root"]),
        "control: state root after redelivery"
    );
    let rc = acfa_receipt::resolve(
        &once,
        rnd,
        &pki,
        e["f"].as_u64().unwrap() as usize,
        rule_of(&e["rule"]),
    );
    assert_eq!(
        rc.admitted.len(),
        ids(&ctl["admitted_ids"]).len(),
        "control: the honest node is still aggregated"
    );
    assert_eq!(
        rc.aggregate,
        Some(i64s(&ctl["aggregate"])),
        "control: the round must still produce the reference's aggregate"
    );
    assert_eq!(
        rc.output_root.to_vec(),
        hx(&ctl["output_root"]),
        "control: output root"
    );
}

/// #85. A THREE-WAY EQUIVOCATOR, DELIVERED BOTH WAYS.
///
/// Two conflicting halves expose exactly ONE pair, so a detector that stops after the first
/// match is indistinguishable from one that derives the closure -- which is why every
/// two-way vector in this file agreed while the reference recorded a SAMPLE of the
/// conflicts. Three halves expose three pairs, and a sample of three depends on arrival
/// order, so the state root does too. Measured on this vector with `deliver` mutated to
/// record only the first pair it finds: forward `fef84bf3...` against the reference's
/// `04cf3303...`. A CRDT whose root depends on arrival order is not a CRDT.
///
/// This also uses `deliver`, which NO golden scenario reaches: they all call
/// `add_contribution`, which is a raw set insert and derives nothing.
#[test]
fn a_three_way_equivocator_lands_on_one_state_root_in_either_delivery_order() {
    let v = vectors();
    let d = &v["delivery_orders"];
    let pki = golden_pki();
    let ctx = golden_ctx();

    let three: Vec<Contribution> = d["equivocator"]
        .as_array()
        .unwrap()
        .iter()
        .map(|c| mk_ctx(ctx, c))
        .collect();
    assert_eq!(three.len(), 3, "the point of this vector is the THIRD half");
    // The honest half is named by node id and rebuilt from `contributions`, so it cannot
    // drift out of step with the vectors the rest of this file already pins.
    let by_id: Vec<Contribution> = v["contributions"]
        .as_array()
        .unwrap()
        .iter()
        .map(|c| mk_ctx(ctx, c))
        .collect();
    let honest: Vec<Contribution> = ids(&d["honest_node_ids"])
        .into_iter()
        .map(|n| {
            by_id
                .iter()
                .find(|c| c.node_id == n)
                .expect("honest node id must name a golden contribution")
                .clone()
        })
        .collect();

    let seq: Vec<Contribution> = three.iter().chain(honest.iter()).cloned().collect();
    let deliver_all = |order: Vec<Contribution>| {
        let mut s = State::new();
        for c in order {
            s.deliver(c, &pki);
        }
        s
    };
    let fwd = deliver_all(seq.clone());
    let rev = deliver_all(seq.iter().rev().cloned().collect());

    assert_eq!(
        fwd.root().to_vec(),
        hx(&d["forward_state_root"]),
        "forward state root disagrees with the reference"
    );
    assert_eq!(
        rev.root().to_vec(),
        hx(&d["reverse_state_root"]),
        "reverse state root disagrees with the reference"
    );
    assert_eq!(
        fwd.root(),
        rev.root(),
        "THE STATE ROOT DEPENDS ON ARRIVAL ORDER. Same updates delivered, permanently \
         different observable state -- strong eventual consistency, which this whole \
         construction is named for, failing."
    );
    assert_eq!(
        proof_leaves(&fwd),
        hexes(&d["proof_leaves"]),
        "the derived proof set must be the CLOSURE the reference derives, not a sample"
    );
    assert_eq!(
        proof_leaves(&rev),
        hexes(&d["reverse_proof_leaves"]),
        "reverse-order proof set"
    );
    assert_eq!(
        proof_leaves(&fwd).len(),
        3,
        "three conflicting halves make three pairs; a smaller set is a sample, and which \
         sample you get depends on what arrived first"
    );
    assert_eq!(
        fwd.convicted(&pki).into_iter().collect::<Vec<u32>>(),
        ids(&d["convicted"]),
        "conviction set"
    );

    let r = acfa_receipt::resolve(
        &fwd,
        d["rnd"].as_u64().unwrap(),
        &pki,
        d["f"].as_u64().unwrap() as usize,
        rule_of(&d["rule"]),
    );
    assert_eq!(
        r.aggregate,
        Some(i64s(&d["aggregate"])),
        "aggregate over the honest remainder"
    );
    assert_eq!(r.output_root.to_vec(), hx(&d["output_root"]), "output root");
    // POSITIVE CONTROL: the honest nodes are still counted. A detector that convicted
    // everyone would satisfy every assertion above and produce no aggregate at all.
    assert_eq!(
        r.admitted.len(),
        ids(&d["admitted_ids"]).len(),
        "the honest majority must survive the equivocator's exclusion"
    );
    assert!(
        !r.admitted.is_empty(),
        "control: conviction is not universal"
    );
}

/// #86. THE SAME EVIDENCE, LEARNED BY GOSSIP INSTEAD OF BY DELIVERY.
///
/// Three replicas each hold ONE of the equivocator's halves, so none can derive anything on
/// its own -- asserted, or the fixture proves nothing. Gossip then unions them. A `merge`
/// that is a plain set union learns the contributions and never forms the evidence their
/// combination implies, so whether misbehaviour is on the record depends on HOW it arrived:
/// the union holds no proofs and convicts nobody, while delivery over the identical
/// contribution set holds the full closure. Conviction feeds `admit`, so the two replicas
/// then admit different sets, compute different aggregates, and publish different roots.
/// Measured on this vector with `merge` mutated back to a plain insert: `7f9d49de...`
/// against the reference's `04cf3303...`.
///
/// No golden scenario called `merge` at all, which is how this stayed invisible.
#[test]
fn evidence_learned_by_merge_convicts_exactly_as_evidence_learned_by_delivery() {
    let v = vectors();
    let m = &v["merge_vs_deliver"];
    let pki = golden_pki();
    let ctx = golden_ctx();

    // Leaf -> contribution over everything this file pins, so a partition is named by the
    // leaves already asserted elsewhere rather than by a second copy of the same bytes.
    let mut known: std::collections::BTreeMap<Vec<u8>, Contribution> = Default::default();
    for c in v["contributions"].as_array().unwrap() {
        let c = mk_ctx(ctx, c);
        known.insert(c.leaf().to_vec(), c);
    }
    for c in v["delivery_orders"]["equivocator"].as_array().unwrap() {
        let c = mk_ctx(ctx, c);
        known.insert(c.leaf().to_vec(), c);
    }

    let parts: Vec<State> = m["partitions"]
        .as_array()
        .unwrap()
        .iter()
        .map(|leaves| {
            let mut s = State::new();
            for l in leaves.as_array().unwrap() {
                let c = known
                    .get(&hx(l))
                    .unwrap_or_else(|| panic!("partition names an unknown leaf {l}"))
                    .clone();
                s.deliver(c, &pki);
            }
            s
        })
        .collect();

    // THE FIXTURE MUST BE NON-DEGENERATE. If a partition already convicts on its own, the
    // merge is not what produced the evidence and this test would pass with `merge` doing
    // nothing at all.
    let want_counts: Vec<usize> = m["partition_proof_counts"]
        .as_array()
        .unwrap()
        .iter()
        .map(|x| x.as_u64().unwrap() as usize)
        .collect();
    let got_counts: Vec<usize> = parts.iter().map(|p| p.e.len()).collect();
    assert_eq!(
        got_counts, want_counts,
        "partition proof counts disagree with the reference"
    );
    assert!(
        got_counts.iter().all(|&n| n == 0),
        "no partition may convict before merging, or the merge is not what formed the proof"
    );

    let merge_all = |order: Vec<&State>| {
        let mut s = State::new();
        for p in order {
            s.merge(p, &pki).expect("merge within bounds");
        }
        s
    };
    let merged = merge_all(parts.iter().collect());
    let merged_rev = merge_all(parts.iter().rev().collect());

    assert_eq!(
        merged.root().to_vec(),
        hx(&m["merged_state_root"]),
        "merged state root disagrees with the reference"
    );
    assert_eq!(
        merged_rev.root().to_vec(),
        hx(&m["reverse_merged_state_root"]),
        "merge is not commutative"
    );
    assert_eq!(
        proof_leaves(&merged),
        hexes(&m["proof_leaves"]),
        "merge must derive the same proof CLOSURE that delivery derives"
    );
    assert_eq!(
        merged.convicted(&pki).into_iter().collect::<Vec<u32>>(),
        ids(&m["convicted"]),
        "conviction set after merge"
    );
    // THE LOAD-BEARING EQUALITY: gossip and delivery are the same state.
    assert_eq!(
        merged.root().to_vec(),
        hx(&m["delivered_state_root"]),
        "a replica that learned the equivocation by GOSSIP holds a different root from one \
         that learned it by DELIVERY, from the same contribution set. The proof set must be \
         a function of the contributions, never of how they arrived."
    );

    let r = acfa_receipt::resolve(
        &merged,
        m["rnd"].as_u64().unwrap(),
        &pki,
        m["f"].as_u64().unwrap() as usize,
        rule_of(&m["rule"]),
    );
    assert_eq!(
        r.aggregate,
        Some(i64s(&m["aggregate"])),
        "aggregate after merge"
    );
    assert_eq!(r.output_root.to_vec(), hx(&m["output_root"]), "output root");
    assert_eq!(
        r.admitted.len(),
        ids(&m["admitted_ids"]).len(),
        "admitted count"
    );
}

/// #90. A DUPLICATE LEAF OFFERED TO `merkle_root`.
///
/// Padding duplicates the sorted MAXIMUM, so a padded tree over `S` is byte-identical to an
/// honest tree over `S + {argmax(S)}` and the root does not commit to its own leaf count.
/// Both implementations must REFUSE rather than return the ambiguous root: silently
/// deduplicating returns a root for a SET while the caller committed to a MULTISET, which
/// is a well-formed but wrong commitment.
///
/// Every leaf set in the `merkle` vectors is distinct, so this branch -- which both sides
/// carry -- was never entered from a vector.
#[test]
fn merkle_root_refuses_a_duplicate_leaf_exactly_as_the_reference_does() {
    let v = vectors();
    let cases = v["merkle_refusals"].as_array().unwrap();
    assert!(
        cases.len() >= 3,
        "the duplicate-leaf corpus has shrunk to {}; a section that quietly emptied would \
         pass every assertion below",
        cases.len()
    );

    // The default hook prints a backtrace for each expected panic, which buries a REAL
    // failure in this file. Restored immediately after the loop.
    let hook = std::panic::take_hook();
    std::panic::set_hook(Box::new(|_| {}));
    let outcomes: Vec<(String, bool)> = cases
        .iter()
        .map(|c| {
            let leaves: Vec<[u8; 32]> = c["leaves"].as_array().unwrap().iter().map(h32).collect();
            let refused = std::panic::catch_unwind(move || merkle_root(&leaves)).is_err();
            (c["name"].as_str().unwrap().to_string(), refused)
        })
        .collect();
    std::panic::set_hook(hook);

    for (c, (name, refused)) in cases.iter().zip(outcomes) {
        assert!(
            refused,
            "[{name}] merkle_root RETURNED a root for a leaf set containing a duplicate. \
             Padding duplicates the sorted maximum, so this root also commits to the set \
             WITHOUT the duplicate -- the CVE-2012-2459 shape, and the root stops committing \
             to its own leaf count."
        );
        assert!(
            c["reference"]["refused"].as_bool().unwrap(),
            "[{name}] CROSS-IMPLEMENTATION DIVERGENCE, issue #90: this crate refuses and the \
             reference returned {:?}. An implementer building from the spec gets a commitment \
             this crate would reject.",
            c["reference"]["root"]
        );
    }

    // POSITIVE CONTROL. Everything above is satisfied by a `merkle_root` that panics on
    // every input, which would be a strictly worse function passing a green test. The
    // control is the same three leaves WITHOUT the duplicate -- the very set the padding
    // collision would have collided with -- and it must produce the reference's root.
    let ctl = &v["merkle_refusal_control"];
    let leaves: Vec<[u8; 32]> = ctl["leaves"].as_array().unwrap().iter().map(h32).collect();
    assert_eq!(
        merkle_root(&leaves).to_vec(),
        hx(&ctl["root"]),
        "the control set must still produce the reference's root, or the refusals above are \
         satisfied by a function that refuses everything"
    );
}

/// #91. THE INPUTS LAYER 1 REFUSES.
///
/// `resolve` is total: when the kernel declines it commits `H("refused|" || rnd)`, so two
/// replicas agree that the round produced NOTHING rather than one of them inventing an
/// answer. Every `scenarios` entry uses uniform, in-range, non-empty tensors and a
/// population meeting its rule's precondition, so that branch was never reached from a
/// vector at all -- and the reference, having no refusal path, computed an aggregate or
/// crashed on all four of these.
///
/// The refusal root is checked against a value the GENERATOR derived in Python from the
/// contract in `src/resolve.rs`, not against a constant this crate computes for itself.
#[test]
fn inputs_layer_one_refuses_commit_the_same_refusal_root_in_both_implementations() {
    let v = vectors();
    let pki = golden_pki();
    let ctx = golden_ctx();
    let cases = v["refusal_scenarios"].as_array().unwrap();
    assert!(
        cases.len() >= 4,
        "the refusal corpus has shrunk to {}; #91 names four inputs and a section that \
         quietly emptied would pass every assertion below",
        cases.len()
    );

    for s in cases {
        let name = s["name"].as_str().unwrap();
        let issue = s["issue"].as_u64().unwrap();
        let rnd = s["rnd"].as_u64().unwrap();

        let mut state = State::new();
        for c in s["entries"].as_array().unwrap() {
            let c = mk_ctx(ctx, c);
            assert!(
                c.signature_valid(&pki),
                "[{name}] the entry must be genuinely signed, or it is filtered by admission \
                 and the kernel never sees the malformed input this vector is about"
            );
            state.add_contribution(c);
        }
        assert_eq!(
            state.root().to_vec(),
            hx(&s["state_root"]),
            "[{name}] state root"
        );

        let r = acfa_receipt::resolve(
            &state,
            rnd,
            &pki,
            s["f"].as_u64().unwrap() as usize,
            rule_of(&s["rule"]),
        );
        // The input must actually REACH the kernel. If admission filtered it out the round
        // would commit the EMPTY sentinel and this test would be measuring the wrong thing.
        assert_eq!(
            r.admitted.len(),
            ids(&s["admitted_ids"]).len(),
            "[{name}] the malformed input must be admitted and reach the kernel, or the \
             refusal under test is really the empty-round sentinel"
        );
        assert!(!r.admitted.is_empty(), "[{name}] nothing was admitted");
        assert_eq!(
            r.aggregate, None,
            "[{name}] the kernel returned an aggregate for an input it must refuse"
        );
        assert_eq!(
            r.output_root.to_vec(),
            hx(&s["rust_refusal_root"]),
            "[{name}] a refused round must commit H(\"refused|\" || rnd), computed \
             independently by the generator"
        );
        assert!(
            !r.population_bound_met,
            "[{name}] a refused round cannot report its robustness precondition as met"
        );

        assert!(
            s["reference"]["refused"].as_bool().unwrap(),
            "[{name}] CROSS-IMPLEMENTATION DIVERGENCE, issue #{issue}: this crate commits the \
             refusal root and the reference did not refuse -- it returned aggregate {:?} at \
             root {:?}, or raised {:?}. A spec that computes where the implementation refuses \
             hands an implementer a kernel that answers confidently on exactly the inputs the \
             design calls unanswerable.",
            s["reference"]["aggregate"],
            s["reference"]["output_root"],
            s["reference"]["error"],
        );
        assert_eq!(
            s["reference"]["output_root"].as_str().map(hex::decode),
            Some(Ok(r.output_root.to_vec())),
            "[{name}] both sides refuse but commit DIFFERENT roots, so the two replicas still \
             disagree about what the round produced"
        );
    }

    // POSITIVE CONTROL. A `resolve` that refused every input would satisfy all of the above.
    // `all-honest-7-krum` is the same code path with well-formed tensors and must still
    // produce the reference's aggregate.
    let ctl = v["scenarios"]
        .as_array()
        .unwrap()
        .iter()
        .find(|s| s["name"] == "all-honest-7-krum")
        .expect("the control scenario must exist");
    let mut state = State::new();
    for c in v["contributions"].as_array().unwrap() {
        state.add_contribution(mk_ctx(ctx, c));
    }
    let r = acfa_receipt::resolve(
        &state,
        ctl["rnd"].as_u64().unwrap(),
        &pki,
        ctl["f"].as_u64().unwrap() as usize,
        rule_of(&ctl["rule"]),
    );
    assert_eq!(
        r.aggregate,
        Some(i64s(&ctl["aggregate"])),
        "control: a well-formed round must still produce the reference's aggregate, or the \
         refusals above are satisfied by a resolve that declines everything"
    );
    assert_ne!(
        r.output_root.to_vec(),
        hx(&v["refusal_scenarios"][0]["rust_refusal_root"]),
        "control: a well-formed round must not commit the refusal root"
    );
}
