//! Cross-implementation agreement with the published reference kernel.
//!
//! THE LOAD-BEARING TEST IN THIS CRATE. Every other test proves that this code agrees
//! with itself; only this one proves it agrees with a SECOND, independently written
//! implementation. A receipt is a promise that anybody can recompute the result -- if
//! the Rust and the published Python disagree on a single byte, that promise is false,
//! and two conforming implementations disagreeing is indistinguishable from one of
//! them being faulty.
//!
//! **Scope of the claim.** Agreement is asserted on every path EXCEPT those listed in
//! `known_divergences` in the golden file, where this implementation is deliberately
//! correct and the reference is deliberately not followed. Those are asserted to DIFFER,
//! so a silently-fixed reference fails this test rather than sliding into unexamined
//! agreement. Today there is exactly one: the reference's Bulyan stage-1 loop
//! under-selects by one whenever `f < 2`.
//!
//! **WHY THE SCENARIO SET WAS NOT ENOUGH, and what the tests below the scenario test are
//! for.** Every entry in `scenarios` uses uniform small tensors, genuine keys, distinct
//! leaves, `add_contribution` rather than `deliver`, and never calls `merge`. So the two
//! implementations were only ever shown inputs they agree on BY CONSTRUCTION: nine
//! divergences (#82, #84-#92) sat under a green run of this file because no vector
//! instantiated the shape that separates them. Each test below instantiates one:
//!
//! | test | shape nothing else reaches | issue |
//! |---|---|---|
//! | `two_signatures_over_one_content_...` | one content, two valid signatures | #84 |
//! | `a_three_way_equivocator_...` | `deliver`, three conflicting halves, both orders | #85 |
//! | `evidence_learned_by_merge_...` | `merge`, evidence split across replicas | #86 |
//! | `merkle_root_refuses_a_duplicate_leaf...` | a leaf offered twice | #90 |
//! | `inputs_layer_one_refuses_...` | ragged / out-of-range / empty / Bulyan-short | #91 |
//!
//! Each carries a POSITIVE CONTROL, because an implementation that convicted everyone, or
//! refused every input, would satisfy the headline assertions and be strictly worse.
//!
//! Vectors are generated by `tests/golden/generate_l2.py` from the reference at
//! arXiv:2607.10305 and committed. Regenerate with:
//!
//! ```sh
//! ACFA_REFERENCE_DIR=/path/to/acfa python3 tests/golden/generate_l2.py \
//!   > tests/golden/vectors_l2.json
//! ```

use acfa_receipt::hash::{enc_tensor, h, merkle_root, prf_ints};
use acfa_receipt::identity::{contrib_msg, Identity, Pki};
use acfa_receipt::{Contribution, EquivProof, Rule, State};
use serde_json::Value;

/// Krum at `f = 1` on this build's fixed-point scale.
///
/// A NAMED FIXTURE, NOT A DEFAULT. A contribution signed under different round parameters is
/// filtered out of the round by `Receipt::issue`, exactly as a foreign `ctx` is, so a test that
/// needs other parameters has to say so rather than inherit these silently.
const PARAMS_DEFAULT: acfa_receipt::RoundParams = acfa_receipt::RoundParams {
    rule: acfa_receipt::Rule::Krum,
    f: 1,
    frac_bits: acfa_receipt::FRAC_BITS,
};

fn vectors() -> Value {
    let raw = include_str!("golden/vectors_l2.json");
    serde_json::from_str(raw).expect("golden vectors parse")
}

fn hx(s: &Value) -> Vec<u8> {
    hex::decode(s.as_str().expect("hex string")).expect("valid hex")
}

/// The context the golden vectors were generated under, read FROM the vectors rather than
/// hardcoded -- a constant here could drift out of step with the generator and the tests would
/// still pass against themselves.
fn golden_ctx() -> [u8; 32] {
    h32(&vectors()["ctx"])
}

fn h32(s: &Value) -> [u8; 32] {
    hx(s).try_into().expect("32 bytes")
}

fn h64(s: &Value) -> [u8; 64] {
    hx(s).try_into().expect("64 bytes")
}

fn i64s(v: &Value) -> Vec<i64> {
    v.as_array()
        .expect("array")
        .iter()
        .map(|x| x.as_i64().expect("i64"))
        .collect()
}

