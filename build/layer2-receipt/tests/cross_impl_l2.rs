#[test]
fn ed25519_public_keys_derive_identically_from_the_same_seed() {
    // If this fails, nothing downstream can match: every leaf contains a signature.
    for id in vectors()["identities"].as_array().unwrap() {
        let node_id = id["node_id"].as_u64().unwrap() as u32;
        let seed: [u8; 32] = hx(&id["seed"]).try_into().unwrap();
        let ours = Identity::from_secret(node_id, &seed);
        assert_eq!(
            ours.public().to_vec(),
            hx(&id["pk"]),
            "public key disagrees for node {node_id}"
        );
    }
}

#[test]
fn signatures_and_contribution_leaves_match_the_reference() {
    // Ed25519 is deterministic (RFC 8032), so the signature is a reproducible constant.
    // Re-signing here rather than trusting the committed bytes is what makes this a
    // cross-implementation check instead of a hash of a hash.
    for c in vectors()["contributions"].as_array().unwrap() {
        let node_id = c["node_id"].as_u64().unwrap() as u32;
        let rnd = c["rnd"].as_u64().unwrap();
        let tensor = i64s(&c["tensor"]);
        let id = Identity::from_secret(node_id, &[node_id as u8; 32]);

        let th = h(&enc_tensor(&tensor));
        assert_eq!(
            th.to_vec(),
            hx(&c["tensor_hash"]),
            "tensor hash, node {node_id}"
        );

        let sig = id.sign(&contrib_msg(
            &golden_ctx(),
            &PARAMS_DEFAULT,
            rnd,
            id.node_id,
            &th,
        ));
        assert_eq!(sig.to_vec(), hx(&c["sig"]), "signature, node {node_id}");

        let ours = Contribution {
            ctx: golden_ctx(),
            sig_preimage: acfa_receipt::identity::PreimageVersion::V2,
            params: PARAMS_DEFAULT,
            rnd,
            node_id,
            tensor,
            sig,
        };
        assert_eq!(ours.leaf().to_vec(), hx(&c["leaf"]), "leaf, node {node_id}");
    }
}

#[test]
fn the_equivocation_proof_matches_the_reference_byte_for_byte() {
    let v = vectors();
    let e = &v["equivocation"];
    let p = &e["proof"];
    let ours = EquivProof {
        ctx: golden_ctx(),
        sig_preimage: acfa_receipt::identity::PreimageVersion::V2,
        params: PARAMS_DEFAULT,
        rnd: p["rnd"].as_u64().unwrap(),
        node_id: p["node_id"].as_u64().unwrap() as u32,
        h1: h32(&p["h1"]),
        h2: h32(&p["h2"]),
        sig1: h64(&p["sig1"]),
        sig2: h64(&p["sig2"]),
    };
    assert_eq!(ours.leaf().to_vec(), hx(&p["leaf"]), "proof leaf");
    assert!(
        p["valid"].as_bool().unwrap(),
        "reference considers it valid"
    );

    // And the canonical constructor must land on the same orientation from either
    // argument order, which is what makes two observers agree.
    let a = (ours.h1, ours.sig1);
    let b = (ours.h2, ours.sig2);
    assert_eq!(
        EquivProof::canonical(
            ours.ctx,
            acfa_receipt::identity::PreimageVersion::V2,
            PARAMS_DEFAULT,
            ours.rnd,
            ours.node_id,
            a,
            b
        )
        .leaf(),
        ours.leaf()
    );
    assert_eq!(
        EquivProof::canonical(
            ours.ctx,
            acfa_receipt::identity::PreimageVersion::V2,
            PARAMS_DEFAULT,
            ours.rnd,
            ours.node_id,
            b,
            a
        )
        .leaf(),
        ours.leaf()
    );
}

#[test]
fn every_scenario_reproduces_the_reference_state_root_admitted_set_and_aggregate() {
    let v = vectors();

    // Rebuild the identities and the PKI exactly as the generator did.
    let pki: Pki = v["identities"]
        .as_array()
        .unwrap()
        .iter()
        .map(|id| {
            let n = id["node_id"].as_u64().unwrap() as u32;
            (n, Identity::from_secret(n, &[n as u8; 32]).public())
        })
        .collect();

    let mk = |c: &Value| Contribution {
        ctx: golden_ctx(),
        sig_preimage: acfa_receipt::identity::PreimageVersion::V2,
        params: PARAMS_DEFAULT,
        rnd: c["rnd"].as_u64().unwrap(),
        node_id: c["node_id"].as_u64().unwrap() as u32,
        tensor: i64s(&c["tensor"]),
        sig: h64(&c["sig"]),
    };

    let base: Vec<Contribution> = v["contributions"]
        .as_array()
        .unwrap()
        .iter()
        .map(mk)
        .collect();
    let alt = mk(&v["equivocation"]["alt"]);
    let pj = &v["equivocation"]["proof"];
    let proof = EquivProof {
        ctx: golden_ctx(),
        sig_preimage: acfa_receipt::identity::PreimageVersion::V2,
        params: PARAMS_DEFAULT,
        rnd: pj["rnd"].as_u64().unwrap(),
        node_id: pj["node_id"].as_u64().unwrap() as u32,
        h1: h32(&pj["h1"]),
        h2: h32(&pj["h2"]),
        sig1: h64(&pj["sig1"]),
        sig2: h64(&pj["sig2"]),
    };

    for s in v["scenarios"].as_array().unwrap() {
        let name = s["name"].as_str().unwrap();
        let rnd = s["rnd"].as_u64().unwrap();
        let f = s["f"].as_u64().unwrap() as usize;
        let rule = match s["rule"].as_str().unwrap() {
            "bulyan" => Rule::Bulyan,
            _ => Rule::Krum,
        };

        let mut state = State::new();
        match name {
            "empty" => {}
            "equivocator-excluded-by-uniqueness" => {
                for c in &base {
                    state.add_contribution(c.clone());
                }
                state.add_contribution(alt.clone());
            }
            "equivocator-convicted-by-proof" => {
                for c in &base {
                    state.add_contribution(c.clone());
                }
                state.add_contribution(alt.clone());
                state.add_proof(proof.clone());
            }
            "five-of-seven-krum" => {
                for c in base.iter().take(5) {
                    state.add_contribution(c.clone());
                }
            }
            "three-undefended" => {
                for c in base.iter().take(3) {
                    state.add_contribution(c.clone());
                }
            }
            _ => {
                for c in &base {
                    state.add_contribution(c.clone());
                }
            }
        }

        assert_eq!(
            state.root().to_vec(),
            hx(&s["state_root"]),
            "[{name}] state root"
        );

        let r = acfa_receipt::resolve(&state, rnd, &pki, f, rule);

        let want_admitted: Vec<Vec<u8>> =
            s["admitted"].as_array().unwrap().iter().map(hx).collect();
        let got_admitted: Vec<Vec<u8>> = r.admitted.iter().map(|l| l.to_vec()).collect();
        assert_eq!(
            got_admitted, want_admitted,
            "[{name}] admitted set and order"
        );

        let want_agg = if s["aggregate"].is_null() {
            None
        } else {
            Some(i64s(&s["aggregate"]))
        };

        // A scenario may be a RECORDED, DELIBERATE divergence from the reference. Those
        // are asserted to differ rather than quietly excluded: if the reference is ever
        // corrected upstream, this test must fail and make us re-decide, instead of the
        // divergence silently becoming agreement nobody re-examined.
        let divergent = v["known_divergences"]
            .as_array()
            .map(|a| a.iter().any(|d| d["scenario"].as_str() == Some(name)))
            .unwrap_or(false);

        if divergent {
            assert_ne!(
                r.aggregate, want_agg,
                "[{name}] recorded as a known divergence but now AGREES with the \
                 reference -- the reference may have been fixed; re-read \
                 known_divergences and re-decide rather than deleting this branch"
            );
            assert_ne!(
                r.output_root.to_vec(),
                hx(&s["output_root"]),
                "[{name}] root"
            );
            continue;
        }

        assert_eq!(r.aggregate, want_agg, "[{name}] aggregate");

        assert_eq!(
            r.output_root.to_vec(),
            hx(&s["output_root"]),
            "[{name}] output root"
        );
    }
}

