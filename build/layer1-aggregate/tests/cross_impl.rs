//! Cross-implementation agreement against the published ACFA reference kernel.
//!
//! This is the test that carries the crate's actual claim. Order-invariance within
//! one implementation only proves that implementation is self-consistent; the
//! property that matters operationally is that an INDEPENDENT implementation, in a
//! different language, computes the same aggregate -- because that is what makes a
//! disagreement between two parties attributable to inputs or conduct rather than
//! to arithmetic.
//!
//! Vectors in `golden/vectors.json` are generated by `golden/generate.py` from the
//! Python reference and committed. Measured corpus: 9 cases, 2784 expected output
//! components, of which 1397 are negative -- so the floor-versus-truncate divergence
//! is genuinely exercised rather than merely asserted in a unit test.
//!
//! A minimal hand-rolled JSON reader is used rather than a dependency: this crate
//! has zero dependencies by design, and a test-only parser is cheaper than making
//! the determinism story rest on someone else's release cadence.

use acfa_aggregate::*;

// ---------- minimal JSON reader, sufficient for this fixed schema ----------

#[derive(Debug, Clone, PartialEq)]
enum J {
    Num(i64),
    Str(String),
    Arr(Vec<J>),
    Obj(Vec<(String, J)>),
}

impl J {
    fn get(&self, k: &str) -> &J {
        match self {
            J::Obj(kv) => &kv.iter().find(|(kk, _)| kk == k).expect("missing key").1,
            _ => panic!("not an object"),
        }
    }
    fn arr(&self) -> &[J] {
        match self {
            J::Arr(a) => a,
            _ => panic!("not an array"),
        }
    }
    fn num(&self) -> i64 {
        match self {
            J::Num(n) => *n,
            _ => panic!("not a number"),
        }
    }
    fn string(&self) -> &str {
        match self {
            J::Str(s) => s,
            _ => panic!("not a string"),
        }
    }
    fn i64_vec(&self) -> Vec<i64> {
        self.arr().iter().map(|x| x.num()).collect()
    }
}

struct P<'a> {
    b: &'a [u8],
    i: usize,
}

impl<'a> P<'a> {
    fn ws(&mut self) {
        while self.i < self.b.len() && (self.b[self.i] as char).is_ascii_whitespace() {
            self.i += 1;
        }
    }
    fn parse(&mut self) -> J {
        self.ws();
        match self.b[self.i] {
            b'{' => {
                self.i += 1;
                let mut kv = Vec::new();
                loop {
                    self.ws();
                    if self.b[self.i] == b'}' {
                        self.i += 1;
                        break;
                    }
                    let k = self.parse().string().to_string();
                    self.ws();
                    assert_eq!(self.b[self.i], b':');
                    self.i += 1;
                    kv.push((k, self.parse()));
                    self.ws();
                    if self.b[self.i] == b',' {
                        self.i += 1;
                    }
                }
                J::Obj(kv)
            }
            b'[' => {
                self.i += 1;
                let mut a = Vec::new();
                loop {
                    self.ws();
                    if self.b[self.i] == b']' {
                        self.i += 1;
                        break;
                    }
                    a.push(self.parse());
                    self.ws();
                    if self.b[self.i] == b',' {
                        self.i += 1;
                    }
                }
                J::Arr(a)
            }
            b'"' => {
                self.i += 1;
                let s = self.i;
                while self.b[self.i] != b'"' {
                    self.i += 1;
                }
                let out = String::from_utf8(self.b[s..self.i].to_vec()).unwrap();
                self.i += 1;
                J::Str(out)
            }
            _ => {
                let s = self.i;
                while self.i < self.b.len()
                    && (self.b[self.i] == b'-' || self.b[self.i].is_ascii_digit())
                {
                    self.i += 1;
                }
                J::Num(
                    std::str::from_utf8(&self.b[s..self.i])
                        .unwrap()
                        .parse()
                        .unwrap(),
                )
            }
        }
    }
}

// ---------- the test ----------

fn load() -> J {
    let raw = include_bytes!("golden/vectors.json");
    P { b: raw, i: 0 }.parse()
}

#[test]
fn rust_matches_the_python_reference_on_every_rule() {
    let doc = load();
    let cases = doc.get("cases").arr();
    assert!(!cases.is_empty(), "golden corpus is empty");

    let mut checked_components = 0usize;
    let mut checked_negative = 0usize;

    for case in cases {
        let n = case.get("n").num();
        let d = case.get("d").num();
        let f = case.get("f").num() as usize;
        let label = format!("n={n} d={d} f={f}");

        let cs: Vec<Contribution> = case
            .get("contributions")
            .arr()
            .iter()
            .map(|c| Contribution {
                tie_key: c.get("tie_key").string().as_bytes().to_vec(),
                v: c.get("v").i64_vec(),
            })
            .collect();

        for (rule, expected, got) in [
            ("mean", case.get("mean").i64_vec(), mean(&cs).unwrap()),
            (
                "trimmed_mean(1/5)",
                case.get("trimmed_mean_1_5").i64_vec(),
                trimmed_mean(&cs, 1, 5).unwrap(),
            ),
            (
                "coord_median_trim",
                case.get("coord_median_trim").i64_vec(),
                coord_median_trim(&cs, f).unwrap(),
            ),
            (
                "krum_aggregate",
                case.get("krum_aggregate").i64_vec(),
                krum_aggregate(&cs, f).unwrap(),
            ),
        ] {
            assert_eq!(
                got.len(),
                expected.len(),
                "{label} {rule}: length disagrees with reference"
            );
            for (k, (g, e)) in got.iter().zip(expected.iter()).enumerate() {
                assert_eq!(
                    g, e,
                    "{label} {rule}: component {k} disagrees with the Python reference \
                     (rust={g}, python={e}) -- a conforming implementation must not diverge here"
                );
                checked_components += 1;
                if *e < 0 {
                    checked_negative += 1;
                }
            }
        }

        let expected_sel: Vec<usize> = case
            .get("multi_krum_selected")
            .i64_vec()
            .into_iter()
            .map(|x| x as usize)
            .collect();
        assert_eq!(
            multi_krum(&cs, f).unwrap(),
            expected_sel,
            "{label} multi_krum: selected SET disagrees with the reference"
        );
    }

    // Guard the guard: a golden file that silently emptied would pass every
    // assertion above without checking anything.
    assert!(
        checked_components > 1000,
        "golden corpus too small to be meaningful ({checked_components} components)"
    );
    assert!(
        checked_negative > 100,
        "golden corpus does not exercise the negative/floor path ({checked_negative} negatives)"
    );
}
